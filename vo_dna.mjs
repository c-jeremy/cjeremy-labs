// vo_dna.mjs: lays the 10 trimmed narration lines (assets/vo_dna/lNN.wav, edge-tts, zh-CN-XiaoxiaoNeural) on the film's
// timeline → assets/dna_vo.wav, and writes the voice's loudness per video frame → src/scenes/dna_vo_env.js.
//   node vo_dna.mjs
import { readFileSync, writeFileSync } from 'node:fs';

export const STARTS = [1.0, 10.1, 19.2, 26.25, 35.8, 46.4, 58.5, 65.45, 71.2, 78.7];
const SR = 44100, DUR = 88, FPS = 24, out = new Float32Array(SR * DUR);

function readWav(p) {                                          // 16-bit PCM mono, as ffmpeg writes it
  const b = readFileSync(p); let o = 12, data = null, ch = 1;
  while (o < b.length) { const id = b.toString('ascii', o, o + 4), n = b.readUInt32LE(o + 4); if (id === 'fmt ') ch = b.readUInt16LE(o + 10); if (id === 'data') { data = b.subarray(o + 8, o + 8 + n); break; } o += 8 + n; }
  const s = new Float32Array(data.length / 2 / ch); for (let i = 0; i < s.length; i++) s[i] = data.readInt16LE(i * 2 * ch) / 32768; return s;
}
STARTS.forEach((t0, i) => {
  const s = readWav(`assets/vo_dna/l${String(i + 1).padStart(2, '0')}.wav`), i0 = Math.round(t0 * SR);
  for (let k = 0; k < s.length && i0 + k < out.length; k++) out[i0 + k] += s[k];
});
const buf = Buffer.alloc(44 + out.length * 2);
buf.write('RIFF', 0); buf.writeUInt32LE(36 + out.length * 2, 4); buf.write('WAVEfmt ', 8); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
buf.writeUInt32LE(SR, 24); buf.writeUInt32LE(SR * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34); buf.write('data', 36); buf.writeUInt32LE(out.length * 2, 40);
for (let i = 0; i < out.length; i++) buf.writeInt16LE(Math.round(Math.max(-1, Math.min(1, out[i])) * 32767), 44 + i * 2);
writeFileSync('assets/dna_vo.wav', buf);

// loudness per frame (RMS over a 60 ms window), smoothed, normalised to 0..1
const env = [], W = Math.round(.06 * SR);
for (let f = 0; f < DUR * FPS; f++) { const c = Math.round(f / FPS * SR); let s = 0; for (let k = c - W / 2; k < c + W / 2; k++) s += (out[k] || 0) ** 2; env.push(Math.sqrt(s / W)); }
const pk = Math.max(...env); let sm = 0;
const norm = env.map(v => (sm += (v / pk - sm) * .55, Math.round(Math.min(1, sm * 1.4) * 100) / 100));
writeFileSync('src/scenes/dna_vo_env.js', `// generated by vo_dna.mjs: the narration's loudness per frame (24 fps), 0..1\nconst VO_ENV = [${norm.join(',')}];\nconst VO_STARTS = ${JSON.stringify(STARTS)};\nconst voAt = t => VO_ENV[Math.max(0, Math.min(VO_ENV.length - 1, Math.round(t * 24)))] || 0;\n`);
console.log('wrote assets/dna_vo.wav and src/scenes/dna_vo_env.js');
